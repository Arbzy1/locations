const VERIFIED_ON = "2026-11-24";

function poly(vertices: Array<[number, number]>): ZoneGeometry {
  const first = vertices[0]!;
  const last = vertices[vertices.length - 1]!;
  const ring =
    first[0] === last[0] && first[1] === last[1]
      ? vertices.map(([lng, lat]) => [lng, lat])
      : [...vertices.map(([lng, lat]) => [lng, lat]), [first[0], first[1]]];
  return {
    type: "MultiPolygon",
    coordinates: [[ring]],
  };
}

function box(west: number, south: number, east: number, north: number): ZoneGeometry {
  return poly([
    [west, south],
    [east, south],
    [east, north],
    [west, north],
  ]);
}

function zone(
  partial: Omit<ChargeScheme, "datasetVersion" | "verifiedOn" | "appliesHours"> & {
    appliesHours?: ChargeScheme["appliesHours"];
  },
): ChargeScheme {
  return {
    ...partial,
    appliesHours: partial.appliesHours ?? HOURS_ALWAYS_EXCEPT_CHRISTMAS,
    verifiedOn: VERIFIED_ON,
    datasetVersion: VERIFIED_ON,
  };
}

