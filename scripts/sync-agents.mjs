#!/usr/bin/env node
/**
 * Keeps every coding agent's rule + ignore files in sync.
 * Usage: npm run agents:sync
 *
 * 1. Rules: runs scripts/sync-rules.mjs (AGENTS.md -> per-agent mirrors), then
 *    verifies every agent's rule file exists.
 * 2. Ignores: `.cursorignore` (outside the managed block) is the source of truth.
 *    It is mirrored to each agent's ignore file (or Claude's permissions.deny).
 * 3. Each agent additionally ignores the other agents' dirs/config files, via a
 *    managed block between AGENTS_SYNC markers.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const BEGIN = "# >>> agents:sync (generated - edit scripts/sync-agents.mjs) >>>";
const END = "# <<< agents:sync <<<";
const HEADER = `# Generated by scripts/sync-agents.mjs from .cursorignore - do not edit by hand.\n`;

/**
 * owns: paths belonging to this agent (hidden from every other agent).
 * rules: rule files that must exist after rules sync.
 * ignore: ignore file this agent reads (null = no file-based ignore support).
 */
const AGENTS = [
  {
    name: "cursor",
    owns: [".cursor/", ".cursorignore", ".cursorindexingignore"],
    rules: [".cursor/rules/00-project.mdc"],
    ignore: ".cursorignore",
  },
  {
    name: "claude",
    owns: [".claude/", "CLAUDE.md"],
    rules: ["CLAUDE.md"],
    ignore: null, // handled via .claude/settings.json permissions.deny
  },
  {
    name: "codex",
    owns: [".codex/"],
    rules: ["AGENTS.md"],
    ignore: null, // Codex has no ignore file; it reads AGENTS.md
  },
  {
    name: "windsurf",
    owns: [".windsurf/", ".windsurfrules", ".codeiumignore"],
    rules: [".windsurfrules"],
    ignore: ".codeiumignore",
  },
  {
    name: "aider",
    owns: [".aider.conf.yml", ".aiderignore", ".aider*", "CONVENTIONS.md"],
    rules: [".aider.conf.yml", "CONVENTIONS.md"],
    ignore: ".aiderignore",
  },
  {
    name: "copilot",
    owns: [".github/copilot-instructions.md"],
    rules: [".github/copilot-instructions.md"],
    ignore: null, // Copilot content exclusion is configured in GitHub settings
  },
];

const read = (rel) => fs.readFileSync(path.join(root, rel), "utf8").replace(/^﻿/, "");

function write(rel, contents) {
  const abs = path.join(root, rel);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  const prev = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : null;
  if (prev === contents) return;
  fs.writeFileSync(abs, contents, "utf8");
  console.log(`wrote ${rel}`);
}

function stripManagedBlock(text) {
  const start = text.indexOf(BEGIN);
  if (start === -1) return text.trimEnd();
  const end = text.indexOf(END, start);
  const after = end === -1 ? "" : text.slice(end + END.length);
  return (text.slice(0, start) + after).trimEnd();
}

function otherAgentPaths(agent) {
  return AGENTS.filter((a) => a !== agent).flatMap((a) => a.owns);
}

function managedBlock(agent) {
  return [
    BEGIN,
    `# Other agents' dirs/config - not relevant to ${agent.name}.`,
    ...otherAgentPaths(agent),
    END,
  ].join("\n");
}

function syncRules() {
  execFileSync(process.execPath, [path.join(root, "scripts", "sync-rules.mjs")], {
    stdio: "inherit",
  });
  const missing = AGENTS.flatMap((a) => a.rules).filter(
    (rel) => !fs.existsSync(path.join(root, rel)),
  );
  if (missing.length) {
    console.error(`missing rule files after sync: ${missing.join(", ")}`);
    process.exit(1);
  }
}

/** gitignore-style pattern -> Claude permission rule(s). Negations are skipped. */
function toClaudeDeny(pattern) {
  if (pattern.startsWith("!")) return [];
  let p = pattern.replace(/^\//, "");
  if (p.endsWith("/")) p += "**";
  if (!p.startsWith("**/") && !p.includes("/")) p = `**/${p}`;
  return [`Read(./${p})`];
}

function syncClaude(sourcePatterns) {
  const rel = ".claude/settings.json";
  const abs = path.join(root, rel);
  const settings = fs.existsSync(abs) ? JSON.parse(read(rel)) : {};
  settings.permissions ??= {};
  // All Read(...) denies are owned by this script; anything else is preserved.
  const kept = (settings.permissions.deny ?? []).filter((r) => !r.startsWith("Read("));
  const claude = AGENTS.find((a) => a.name === "claude");
  const generated = [...sourcePatterns, ...otherAgentPaths(claude)].flatMap(toClaudeDeny);
  settings.permissions.deny = [...kept, ...new Set(generated)];
  write(rel, `${JSON.stringify(settings, null, 2)}\n`);
}

function syncIgnores() {
  const source = stripManagedBlock(read(".cursorignore"));
  const patterns = source
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("#"));

  for (const agent of AGENTS) {
    if (!agent.ignore) continue;
    const body = agent.ignore === ".cursorignore" ? source : `${HEADER}\n${source}`;
    write(agent.ignore, `${body}\n\n${managedBlock(agent)}\n`);
  }

  syncClaude(patterns);
}

syncRules();
syncIgnores();
console.log("agents:sync complete");
