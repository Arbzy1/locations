#!/usr/bin/env node
/**
 * Regenerates tool-specific agent rule files from AGENTS.md.
 * Usage: npm run rules:sync
 *
 * Cursor rules are written as `.cursor/rules/{order}-{name}.mdc`.
 * Markers: <!-- sync:cursor-rule name="..." order="10" alwaysApply="true" globs="..." -->
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const agentsPath = path.join(root, "AGENTS.md");
const rulesDir = path.join(root, ".cursor", "rules");

const HEADER = `<!-- Generated by scripts/sync-rules.mjs from AGENTS.md - do not edit by hand. -->\n`;

/** Supports: name="..." order="10" globs="..." alwaysApply="true" */
const CURSOR_RULE_RE =
  /<!--\s*sync:cursor-rule\s+([^>]+?)-->([\s\S]*?)<!--\s*\/sync:cursor-rule\s*-->/g;

function parseAttrs(attrStr) {
  const attrs = {};
  for (const m of attrStr.matchAll(/(\w+)="([^"]*)"/g)) {
    attrs[m[1]] = m[2];
  }
  return attrs;
}

function stripCursorRuleMarkers(md) {
  return md
    .replace(CURSOR_RULE_RE, (_m, _attrs, body) => body.trim())
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

function extractCursorRules(md) {
  const rules = [];
  for (const match of md.matchAll(CURSOR_RULE_RE)) {
    const attrs = parseAttrs(match[1]);
    if (!attrs.name) continue;
    const order = attrs.order ? String(attrs.order).padStart(2, "0") : null;
    rules.push({
      name: attrs.name,
      order,
      globs: attrs.globs || null,
      alwaysApply: attrs.alwaysApply === "true",
      body: match[2].trim(),
    });
  }
  return rules;
}

function ensureDir(filePath) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
}

function writeFile(rel, contents) {
  const abs = path.join(root, rel);
  ensureDir(abs);
  fs.writeFileSync(abs, contents, "utf8");
  console.log(`wrote ${rel}`);
}

function frontmatter(rule) {
  const lines = [`description: ${rule.name} (synced from AGENTS.md)`];
  if (rule.globs) lines.push(`globs: ${rule.globs}`);
  lines.push(`alwaysApply: ${rule.alwaysApply ? "true" : "false"}`);
  return `---\n${lines.join("\n")}\n---`;
}

function filenameFor(rule) {
  if (rule.order) return `${rule.order}-${rule.name}.mdc`;
  return `${rule.name}.mdc`;
}

function main() {
  const checkOnly = process.argv.includes("--check");
  if (!fs.existsSync(agentsPath)) {
    console.error("AGENTS.md not found at", agentsPath);
    process.exit(1);
  }

  const agents = fs.readFileSync(agentsPath, "utf8");
  const body = stripCursorRuleMarkers(agents);
  const cursorRules = extractCursorRules(agents);

  /** @type {Map<string, string>} */
  const expected = new Map();
  expected.set(
    ".cursor/rules/00-project.mdc",
    `---
description: Project conventions from AGENTS.md (source of truth)
alwaysApply: true
---

${HEADER}
${body}
`,
  );

  for (const rule of cursorRules) {
    expected.set(
      `.cursor/rules/${filenameFor(rule)}`,
      `${frontmatter(rule)}

${HEADER}
# ${rule.name}

${rule.body}
`,
    );
  }

  expected.set("CLAUDE.md", `${HEADER}\n${body}\n`);
  expected.set(".windsurfrules", `${HEADER}\n${body}\n`);
  expected.set("CONVENTIONS.md", `${HEADER}\n${body}\n`);
  expected.set(
    ".aider.conf.yml",
    `# Generated by scripts/sync-rules.mjs - do not edit by hand.\nread: CONVENTIONS.md\n`,
  );
  expected.set(".github/copilot-instructions.md", `${HEADER}\n${body}\n`);

  if (checkOnly) {
    const normalize = (s) => s.replace(/\r\n/g, "\n");
    const drifted = [];
    for (const [rel, contents] of expected) {
      const abs = path.join(root, rel);
      if (!fs.existsSync(abs)) {
        drifted.push(`${rel} (missing)`);
        continue;
      }
      const actual = fs.readFileSync(abs, "utf8");
      if (normalize(actual) !== normalize(contents)) {
        drifted.push(rel);
      }
    }
    if (fs.existsSync(rulesDir)) {
      for (const existing of fs.readdirSync(rulesDir)) {
        if (existing.endsWith(".mdc") && !expected.has(`.cursor/rules/${existing}`)) {
          drifted.push(`.cursor/rules/${existing} (extra)`);
        }
      }
    }
    if (drifted.length > 0) {
      console.error("rules:sync --check failed; run `npm run rules:sync`:\n  " + drifted.join("\n  "));
      process.exit(1);
    }
    console.log("rules:sync --check ok");
    return;
  }

  fs.mkdirSync(rulesDir, { recursive: true });
  for (const existing of fs.readdirSync(rulesDir)) {
    if (existing.endsWith(".mdc")) {
      fs.unlinkSync(path.join(rulesDir, existing));
    }
  }

  for (const [rel, contents] of expected) {
    writeFile(rel, contents);
  }

  console.log("rules:sync complete");
}

main();
