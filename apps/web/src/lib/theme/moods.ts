export type MoodId = (typeof COLOUR_MOODS)[number]["id"];

const MOOD_BY_ID = new Map(COLOUR_MOODS.map((mood) => [mood.id, mood]));

export function isMoodId(value: string | null | undefined): value is MoodId {
  return Boolean(value && MOOD_BY_ID.has(value));
}

export function resolveMoodId(value: string | null | undefined): MoodId {
  return isMoodId(value) ? value : DEFAULT_MOOD_ID;
}

export function getMood(id: string | null | undefined): ColourMood {
  return MOOD_BY_ID.get(resolveMoodId(id)) ?? COLOUR_MOODS[0];
}

export function shuffleMoodId(current: string): MoodId {
  const others = COLOUR_MOODS.map((mood) => mood.id).filter((id) => id !== current);
  if (others.length === 0) return resolveMoodId(current);
  return others[Math.floor(Math.random() * others.length)] as MoodId;
}

function decls(tokens: MoodTokens): string {
  const lines = Object.entries(TOKEN_CSS).map(([key, cssName]) => `${cssName}: ${tokens[key as keyof MoodTokens]};`);
  lines.push("--admin: var(--visit);");
  return lines.join(" ");
}

export function moodStyleSheet(): string {
  return COLOUR_MOODS.flatMap((mood) => [
    `[data-theme="dark"][data-mood="${mood.id}"] { ${decls(mood.dark)} }`,
    `[data-theme="light"][data-mood="${mood.id}"] { ${decls(mood.light)} }`,
  ]).join("\n");
}

export function injectMoodStyles(): void {
  if (typeof document === "undefined") return;
  const id = "locations-moods";
  let el = document.getElementById(id) as HTMLStyleElement | null;
  if (!el) {
    el = document.createElement("style");
    el.id = id;
    document.head.appendChild(el);
  }
  el.textContent = moodStyleSheet();
}
